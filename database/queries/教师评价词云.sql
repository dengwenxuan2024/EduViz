-- ============================================================
-- 教师评价关键词词频统计
-- 说明：提取 evaluations 表评价文本，按教师分组统计关键词频次
-- 注意：本SQL假设评价文本中关键词以'，'分隔，实际需根据数据格式调整
-- ============================================================

SELECT 
    teacher_name,
    evaluation AS keyword
FROM evaluations
WHERE teacher_name = '张老师'  -- 可替换为 '李老师' 或 '王老师'
LIMIT 100;